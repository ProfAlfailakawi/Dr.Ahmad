/**
 * مصطلحات واجهة النظام فقط.
 * لا تُستخدم لحفظ المحتوى ولا لتعديل المقالات أو الكتب أو الأبحاث أو السيرة.
 */
export function systemUiTerminology(value: string) {
  return String(value || '')
    .replace(/التقنيات/g, 'التكنولوجيات')
    .replace(/تقنيات/g, 'تكنولوجيات')
    .replace(/للتقنية/g, 'للتكنولوجيا')
    .replace(/بالتقنية/g, 'بالتكنولوجيا')
    .replace(/والتقنية/g, 'والتكنولوجيا')
    .replace(/التقنية/g, 'التكنولوجيا')
    .replace(/تقني(?:اً|ًا)/g, 'تكنولوجيًا')
    .replace(/تقنية/g, 'تكنولوجيا')
    .replace(/تقنيّة/g, 'تكنولوجيا')
    .replace(/تقني/g, 'تكنولوجي')
}
