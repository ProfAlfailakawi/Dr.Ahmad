import { motion, useReducedMotion } from 'framer-motion'
import { EASE, FadeUp, Page, PageHead } from '../components/ui'
import { Newsletter } from '../components/extras'
import { useSeo } from '../components/seo'
import { faqs, inboxLinks, testimonials } from '../data'
import { useExtras } from '../lib/content'

type LiveInboxItem = {
  id: string
  title?: string
  note?: string
  url?: string
  message?: string
  reply?: string
  tone?: string
  autoGenerated?: boolean
  status?: string
  published?: boolean
  createdAt?: { seconds?: number }
}

type LiveFaq = {
  id: string
  q?: string
  a?: string
  question?: string
  answer?: string
  status?: string
  published?: boolean
  createdAt?: { seconds?: number }
}

type WeeklyQuestion = {
  id: string
  ar?: string
  arNote?: string
  take?: string
  status?: string
  published?: boolean
  createdAt?: { seconds?: number }
}

function smartPulse() {
  const now = new Date()
  const dayIndex = Math.floor(Date.now() / 86_400_000)
  const threeDayPulse = Math.floor(dayIndex / 3)
  const weekendNudge = [4, 5].includes(now.getDay()) ? 1 : 0
  const monthTurnNudge = now.getDate() <= 3 ? 1 : 0
  return threeDayPulse + weekendNudge + monthTurnNudge
}

const pulse = smartPulse()
const rotate = <T,>(arr: T[]): T[] => arr.length ? [...arr.slice(pulse % arr.length), ...arr.slice(0, pulse % arr.length)] : arr
const isPublished = (item: { status?: string; published?: boolean }) => item.published !== false && item.status !== 'draft' && item.status !== 'hidden'
const clean = (value = '') => value.replace(/\s+/g, ' ').trim()

export default function Inbox() {
  useSeo({
    title: 'رسائل على الهامش',
    path: '/inbox',
    description: 'رسائل قصيرة تفتح زاوية جديدة، ومختارات وأسئلة من التعليم والتربية والتقنية.',
  })
  const reduce = useReducedMotion()
  const liveInbox = useExtras<LiveInboxItem>('site_inbox', { realtime: true })
  const liveFaqs = useExtras<LiveFaq>('site_faqs', { realtime: true })
  const liveQuestions = useExtras<WeeklyQuestion>('site_questions', { realtime: true })

  const letters = liveInbox
    .filter(isPublished)
    .filter((item) => Boolean(item.message) || item.autoGenerated === true)
    .map((item) => ({
      id: item.id,
      message: clean(item.message || [item.title, item.note].filter(Boolean).join(' — ')),
      reply: clean(item.reply),
      tone: clean(item.tone),
    }))
    .filter((item) => item.message)
    .filter((item, index, all) => all.findIndex((candidate) => candidate.message === item.message) === index)

  const featuredLetter = letters[0]
  const letterArchive = letters.slice(1, 7)

  const links = [
    ...liveInbox
      .filter(isPublished)
      .filter((item) => !item.message && item.title && item.note)
      .map((item) => ({ title: clean(item.title), note: clean(item.note), url: clean(item.url) })),
    ...inboxLinks,
  ].filter((item, index, all) => all.findIndex((candidate) => clean(candidate.url || candidate.title) === clean(item.url || item.title)) === index)

  const questions = [
    ...liveFaqs
      .filter(isPublished)
      .map((item) => ({ q: clean(item.q || item.question), a: clean(item.a || item.answer) }))
      .filter((item) => item.q && item.a),
    ...liveQuestions
      .filter(isPublished)
      .map((item) => ({ q: clean(item.ar), a: clean(item.take || item.arNote) }))
      .filter((item) => item.q && item.a),
    ...rotate(faqs),
  ].filter((item, index, all) => all.findIndex((candidate) => clean(candidate.q) === clean(item.q)) === index)

  return (
    <Page>
      <PageHead label="رسائل على الهامش" title="رسالةٌ تفتح نافذة." sub="صوت قارئ، وفكرة تستحق أن تبقى في الحوار." />

      {/* الرسالة الأحدث */}
      <section className="border-b border-hair px-6 py-16 md:px-11 md:py-24">
        <div className="mx-auto max-w-shell">
          <FadeUp>
            <span className="text-[.76rem] font-semibold uppercase text-accent">الرسالة الأحدث</span>
          </FadeUp>
          {featuredLetter ? (
            <div className="mt-8 grid gap-8 lg:grid-cols-[1.35fr_.65fr] lg:items-end">
              <FadeUp delay={0.06}>
                <blockquote className="relative overflow-hidden rounded-[2rem] border border-hair bg-wash px-7 py-9 md:px-11 md:py-12">
                  <span className="absolute right-8 top-3 font-display text-[5rem] leading-none text-accent/15">”</span>
                  <p className="relative font-display text-[clamp(1.2rem,2.2vw,1.72rem)] font-light leading-[2] text-ink/92">
                    {featuredLetter.message}
                  </p>
                </blockquote>
              </FadeUp>
              {featuredLetter.reply && (
                <FadeUp delay={0.13}>
                  <div className="border-s-2 border-accent ps-6">
                    <span className="text-[.72rem] font-semibold uppercase text-accent">ردّي المختصر</span>
                    <p className="mt-3 font-display text-[1.06rem] leading-[1.95] text-ink/82">{featuredLetter.reply}</p>
                  </div>
                </FadeUp>
              )}
            </div>
          ) : (
            <FadeUp delay={0.06}>
              <div className="mt-8 rounded-[2rem] border border-hair bg-wash p-8 text-soft">
                الرسالة الأولى تُكتب الآن، وستظهر هنا تلقائيًا.
              </div>
            </FadeUp>
          )}

          {letterArchive.length > 0 && (
            <div className="mt-12 grid gap-5 md:grid-cols-2 lg:grid-cols-3">
              {letterArchive.map((letter, index) => (
                <FadeUp key={letter.id} delay={Math.min(index * 0.05, 0.25)}>
                  <article className="h-full rounded-2xl border border-hair bg-canvas p-6">
                    <p className="font-display text-[1.02rem] font-light leading-[1.9] text-ink/84">{letter.message}</p>
                  </article>
                </FadeUp>
              ))}
            </div>
          )}
        </div>
      </section>

      {/* شهادات */}
      <section className="border-b border-hair px-6 py-16 md:px-11 md:py-20">
        <div className="mx-auto max-w-shell">
          <FadeUp>
            <span className="text-[.76rem] font-semibold uppercase text-accent">ماذا قالوا</span>
          </FadeUp>
          <div className="mt-8 grid gap-6 md:grid-cols-2">
            {rotate(testimonials).map((t, i) => (
              <motion.blockquote
                key={i}
                initial={reduce ? false : { opacity: 0, y: 24 }}
                whileInView={{ opacity: 1, y: 0 }}
                viewport={{ once: true, amount: 0.2 }}
                transition={{ duration: 0.7, delay: i * 0.08, ease: EASE }}
                className="relative rounded-2xl border border-hair bg-wash p-8 md:p-9"
              >
                <span className="absolute right-7 top-3 font-display text-[3.5rem] leading-none text-accent/20">”</span>
                <p className="relative font-display text-[1.16rem] font-light leading-[1.95] text-ink/90">{t.quote}</p>
              </motion.blockquote>
            ))}
          </div>
        </div>
      </section>

      {/* روابط منتقاة */}
      <section className="border-b border-hair px-6 py-16 md:px-11 md:py-20">
        <div className="mx-auto max-w-shell">
          <FadeUp>
            <span className="text-[.76rem] font-semibold uppercase text-accent">روابط تستحق وقتك</span>
          </FadeUp>
          <ul className="mt-8">
            {rotate(links).map((l, i) => (
              <FadeUp key={`${l.url || 'note'}-${l.title}`} delay={i * 0.06}>
                <li className={i === 0 ? '' : 'border-t border-hair'}>
                  {l.url ? (
                    <a
                      href={l.url}
                      target="_blank"
                      rel="noreferrer"
                      data-hover
                      className="group flex items-center gap-6 py-7 transition-[padding] duration-400 hover:pe-3"
                    >
                      <span className="flex-1">
                        <span className="block font-display text-[1.2rem] font-medium leading-[1.6] text-ink transition-colors group-hover:text-accent md:text-[1.35rem]">{l.title}</span>
                        <span className="mt-1.5 block text-[.88rem] font-light text-soft">{l.note}</span>
                      </span>
                      <span className="shrink-0 text-[1.2rem] text-accent opacity-0 transition-all duration-400 group-hover:opacity-100">←</span>
                    </a>
                  ) : (
                    <div className="py-7">
                      <span className="block font-display text-[1.2rem] font-medium leading-[1.6] text-ink md:text-[1.35rem]">{l.title}</span>
                      <span className="mt-1.5 block text-[.88rem] font-light leading-relaxed text-soft">{l.note}</span>
                    </div>
                  )}
                </li>
              </FadeUp>
            ))}
          </ul>
        </div>
      </section>

      {/* أسئلة تصلني */}
      <section className="px-6 py-16 md:px-11 md:py-20">
        <div className="mx-auto max-w-shell">
          <FadeUp>
            <span className="text-[.76rem] font-semibold uppercase text-accent">أسئلة تصلني</span>
          </FadeUp>
          <div className="mt-9 grid gap-10 md:grid-cols-3">
            {questions.slice(0, 12).map((f, i) => (
              <FadeUp key={f.q} delay={i * 0.07}>
                <div className="border-t-2 border-accent pt-5">
                  <h3 className="font-display text-[1.18rem] font-medium leading-[1.6] text-ink">{f.q}</h3>
                  <p className="mt-3.5 text-[.98rem] font-light leading-[1.9] text-ink/80">{f.a}</p>
                </div>
              </FadeUp>
            ))}
          </div>

          <FadeUp delay={0.12}>
            <div className="mt-16">
              <Newsletter />
            </div>
          </FadeUp>
        </div>
      </section>
    </Page>
  )
}
