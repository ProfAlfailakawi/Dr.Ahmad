const data = JSON.parse(readFileSync(SOURCE, 'utf8'))
const changes = []
for (const [slug, episode] of Object.entries(data.episodes || {})) {
  Object.values(episode).forEach((turn, index) => {
    const before = String(turn.text || '')
    let after = before
    for (const [from, to] of rules) after = after.replace(from, to)
    if (after !== before) { turn.text = after; changes.push({ slug, turn: index + 1, before, after }) }
  })
}

const joined = Object.values(data.episodes).flatMap((ep) => Object.values(ep)).map((t) => t.text).join('\n')
const leftovers = ['من خلال', 'بالإضافة', 'نظرا ل', 'أثناء', ' نحو '].filter((needle) => joined.includes(needle))
const recorded = Number(data.review?.conversationalFlowChangedTurns || 0)
assert.ok(changes.length >= 35 || recorded >= 35, `لا تعديلات جديدة ولا سجل سابق للجولة الحوارية (${changes.length}/${recorded})`)
assert.deepEqual(leftovers, [], `بقيت وصلات كتابية: ${leftovers.join('، ')}`)

data.review = {
  ...(data.review || {}),
  conversationalFlowReviewed: true,
  conversationalFlowChangedTurns: Math.max(changes.length, recorded),
  conversationalFlowVersion: '2026-08-22-kuwaiti-conversation-v1',
}

if (WRITE) {
  writeFileSync(SOURCE, JSON.stringify(data) + '\n')
  writeFileSync(resolve(ROOT, 'podcast-audits/kuwaiti-conversational-flow-report.json'), JSON.stringify({
    generatedAt: new Date().toISOString(), episodesReviewed: Object.keys(data.episodes).length,
    changedTurns: changes.length, leftovers: leftovers.length, changes,
  }, null, 2) + '\n')
}

console.log(`✓ جولة النفس المحكي: ${Object.keys(data.episodes).length} حلقة · ${changes.length} تعديل · بقايا=${leftovers.length}`)
console.log(WRITE ? '✓ كُتب المصدر والتقرير' : 'ℹ تدقيق فقط')
