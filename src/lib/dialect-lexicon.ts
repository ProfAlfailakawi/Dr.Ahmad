const SYNONYM = new Map<string, string>()
for (const line of CLUSTERS) {
  const words = normalize(line).split(' ').filter((w) => w.length >= 2)
  if (!words.length) continue
  const root = words[0]
  for (const word of words) if (!SYNONYM.has(word)) SYNONYM.set(word, root)
}

/* سوابق عربية شائعة تُقشر قبل البحث: «بالعيال» و«والألعاب» يجب أن تصلا إلى
   «عيال» و«ألعاب» — وإلا لم يفهم الموقع نصف ما يكتبه الزائر بلهجته. */
const PREFIX = /^(?:وال|فال|بال|كال|لل|ال|و|ف|ب|ك|ل)/

/** يردّ كلمةً إلى جذرها الدلاليّ، بعد تجريد سابقةٍ إن وُجدت */
export function toRoot(word: string): string {
  const key = normalize(word)
  if (SYNONYM.has(key)) return SYNONYM.get(key)!
  const bare = key.replace(PREFIX, '')
  if (bare.length >= 3 && SYNONYM.has(bare)) return SYNONYM.get(bare)!
  return SYNONYM.get(key) || key
}

export const LEXICON_SIZE = SYNONYM.size
