/* بناء الخريطة: كل كلمة ← جذر عنقودها (أوّل كلمةٍ فيه، مطبَّعة) */
function buildMap() {
  const map = new Map()
  for (const line of CLUSTERS) {
    const words = normalize(line).split(' ').filter((word) => word.length >= 2)
    if (!words.length) continue
    const root = words[0]
    for (const word of words) {
      if (!map.has(word)) map.set(word, root)
    }
  }
  return map
}

const SYNONYM = buildMap()

/** يردّ كلمةً إلى جذرها الدلاليّ إن وُجد، وإلا يعيدها كما هي */
export function toRoot(word) {
  const key = normalize(word)
  return SYNONYM.get(key) || key
}

/** حجم القاموس — للتقارير والاختبار */
export const LEXICON_SIZE = SYNONYM.size

/* ═══ اختبار ذاتي ═══
   يشترط أن يكون هذا الملف هو المُشغَّل مباشرةً: وإلا لسحب scholar.mjs — الذي
   يستورده — اختبارَه هو فخرج قبل أن تعمل اختبارات scholar نفسها. */
const IS_MAIN = import.meta.url === `file://${process.argv[1]}`
if (IS_MAIN && process.argv.includes('--self-test')) {
  const assert = (c, m) => { if (!c) throw new Error(`✘ ${m}`) }

  /* ★ اللهجات الثلاث تلتقي عند جذرٍ واحد */
  assert(toRoot('عيال') === toRoot('اطفال'), '★ «عيال» (كويتي) = «أطفال» (فصيح)')
  assert(toRoot('يهال') === toRoot('اطفال'), '★ «يهال» (بدوي) = «أطفال»')
  assert(toRoot('مدارس') === toRoot('المؤسسه التعليميه'.split(' ')[0]) || toRoot('مدارس') === toRoot('مدرسه'), 'المدرسة والمؤسسة التعليمية')
  assert(toRoot('اختبار') === toRoot('امتحان'), '«اختبار» = «امتحان»')
  assert(toRoot('اختبارات') === toRoot('امتحان'), 'الجمع كذلك')
  assert(toRoot('جوال') === toRoot('هاتف'), '«جوال» = «هاتف»')
  assert(toRoot('موبايل') === toRoot('تلفون'), '«موبايل» = «تلفون»')
  assert(toRoot('فلوس') === toRoot('مال'), '«فلوس» (عامي) = «مال»')
  assert(toRoot('سوشيل') === toRoot('سوشيال'), 'صور المنصة تلتقي')

  /* ★ لا يخلط المتباعد: التعليم غير التقنية */
  assert(toRoot('طالب') !== toRoot('روبوت'), '★ الطالب ليس روبوتاً')
  assert(toRoot('خوف') !== toRoot('نجاح'), 'الخوف ليس النجاح')

  /* ★ لا كلمةَ في عنقودين: أوّل تعيينٍ يفوز، فكلمةٌ مكرّرةٌ تُربط بجذرٍ عشوائيّ
     حسب ترتيب العناقيد — وهذا ما أوقع «عيال» بين الطالب والطفل. نمنعه بالبناء. */
  const seen = new Map()
  const dupes = []
  for (const line of CLUSTERS) {
    for (const word of normalize(line).split(' ').filter((w) => w.length >= 2)) {
      if (seen.has(word) && seen.get(word) !== line) dupes.push(word)
      else seen.set(word, line)
    }
  }
  assert(dupes.length === 0, `★ كلماتٌ في أكثر من عنقود: ${[...new Set(dupes)].join('، ')}`)

  /* الكلمة المجهولة تعود كما هي مطبَّعة */
  assert(toRoot('نفطيات') === 'نفطيات', 'المجهول يُطبَّع ويُعاد')
  assert(toRoot('أطفال') === toRoot('اطفال'), 'الهمزة لا تفرّق')

  console.log(`✓ اختبارات القاموس الجبّار: 14/14 · ${LEXICON_SIZE} كلمة في ${CLUSTERS.length} عنقوداً`)
  process.exit(0)
}
