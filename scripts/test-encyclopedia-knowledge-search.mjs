import assert from 'node:assert/strict'
import { readFileSync } from 'node:fs'

const read = (path) => readFileSync(path, 'utf8')
const passages = JSON.parse(read('src/data/book-passages.json'))
const teaching = JSON.parse(read('src/data/encyclopedia-teaching-map.json'))
const catalog = JSON.parse(read('src/data/encyclopedia-videos-fallback.json'))
const transcripts = JSON.parse(read('src/data/encyclopedia-video-transcripts.json'))
const searchLib = read('src/lib/encyclopedia-knowledge-search.ts')
const resultsUi = read('src/components/EncyclopediaKnowledgeResults.tsx')
const portal = read('src/components/EncyclopediaPortal.tsx')
const server = read('src/server/encyclopedia-videos.mjs')
const builder = read('scripts/build-encyclopedia-transcript-index.mjs')
const allNotes = read('scripts/test-all-user-notes.mjs')

const encyclopedia = passages.books.find((book) => book.slug === 'encyclopedia')
const slideTopics = Object.values(teaching).flatMap((door) => Object.keys(door.topics || {}))

assert.ok(encyclopedia?.passages?.length >= 370, 'يجب أن يبقى متن الموسوعة مفهرساً كاملاً')
assert.equal(slideTopics.length, 24, 'يجب ربط محاور العروض الأربعة والعشرين')
assert.ok(catalog.videos.length >= 160, 'يجب أن يغطي فهرس الفيديو القناة كاملة')
assert.equal(transcripts.catalogCount, catalog.videos.length)
assert.equal(Object.keys(transcripts.videos || {}).length, catalog.videos.length)
assert.match(searchLib, /scoreSmartFields/)
assert.match(searchLib, /passageLimit/)
assert.match(searchLib, /slideLimit/)
assert.match(resultsUi, /بين الفيديو والكتاب والعرض/)
assert.match(resultsUi, /اللحظة/)
assert.match(resultsUi, /افتح صفحة/)
assert.match(resultsUi, /encyclopedia\.pdf#page=/, 'زر الكتاب يجب أن يقفز إلى صفحة PDF الدقيقة')
assert.match(resultsUi, /`knowledge-\$\{moment\.videoId\}-\$\{moment\.startSeconds\}` === playingVideoInstance/, 'اختيار لحظة ثانية في الفيديو نفسه يجب أن يحافظ على توقيتها')
assert.match(resultsUi, /اعرض الشرائح/)
assert.match(resultsUi, /w-\[82vw\]/, 'نتائج الهاتف يجب أن تكشف طرف البطاقة التالية')
assert.match(portal, /searchEncyclopediaVideoMoments/)
assert.match(portal, /searchEncyclopediaKnowledge/)
assert.match(portal, /playingStartSeconds/)
assert.match(portal, /EncyclopediaKnowledgeResults/)
assert.match(server, /seedBundledTranscriptIndex/)
assert.match(server, /fullSweep/)
assert.match(builder, /ENCYCLOPEDIA_TRANSCRIBE_ENDPOINT/)
assert.doesNotMatch(allNotes, /detailsRef\.current\.open = true/, 'اختبار GitHub القديم لا يجوز أن يطلب detailsRef بعد تحويل الأبواب إلى حالة متحكم بها')
assert.match(allNotes, /open=\{isOpen\}/)

console.log(`✓ محرك المعرفة يربط ${catalog.videos.length} فيديو و${encyclopedia.passages.length} مقطعاً و${slideTopics.length} محور شرائح`)
console.log('✓ البحث المنطوق يفتح الفيديو من الثانية، ويعرض صفحة الكتاب والشرائح في بطاقة موحدة')
console.log('✓ اختبار GitHub القديم detailsRef أزيل نهائياً')
