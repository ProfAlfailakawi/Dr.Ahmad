const data = JSON.parse(readFileSync(SOURCE, 'utf8'))
const changes = []
for (const [slug, episode] of Object.entries(data.episodes)) {
  for (let index = 0; index < episode.length; index += 1) {
    const before = String(episode[index].text || '')
    let after = before
    for (const [pattern, replacement] of rules) after = after.replace(pattern, replacement)
    if (after !== before) {
      episode[index].text = after
      changes.push({ slug, turn: index + 1, before, after })
    }
  }
}

const leftovers = []
for (const [slug, episode] of Object.entries(data.episodes)) {
  episode.forEach((turn, index) => {
    for (const [label, pattern] of spokenWrittenPatterns) {
      if (pattern.test(turn.text)) leftovers.push({ slug, turn: index + 1, label, text: turn.text })
    }
  })
}

const recordedChanges = Number(data.review?.spokenSixChangedTurns || 0)
assert.ok(changes.length >= 90 || recordedChanges >= 90,
  `لا تعديلات جديدة ولا سجل سابق يبرهن تنظيف الست (${changes.length}/${recordedChanges})`)
assert.deepEqual(leftovers, [], `بقيت عبارات كتابية: ${JSON.stringify(leftovers, null, 2)}`)

