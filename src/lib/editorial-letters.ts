function hash(value: string) {
  let result = 2166136261
  for (let index = 0; index < value.length; index += 1) {
    result ^= value.charCodeAt(index)
    result = Math.imul(result, 16777619)
  }
  return result >>> 0
}

function shuffled<T>(items: readonly T[], seed: number): T[] {
  const output = [...items]
  let state = seed || 1
  const next = () => {
    state = Math.imul(state ^ (state >>> 15), 1 | state)
    state ^= state + Math.imul(state ^ (state >>> 7), 61 | state)
    return ((state ^ (state >>> 14)) >>> 0) / 4294967296
  }
  for (let index = output.length - 1; index > 0; index -= 1) {
    const target = Math.floor(next() * (index + 1))
    ;[output[index], output[target]] = [output[target], output[index]]
  }
  return output
}

function randomSeed() {
  if (typeof crypto !== 'undefined' && typeof crypto.getRandomValues === 'function') {
    return crypto.getRandomValues(new Uint32Array(1))[0]
  }
  return hash(`${Date.now()}:${Math.random()}`)
}

function pool(): EditorialLetter[] {
  return SCENARIOS.flatMap((scenario) =>
    scenario.openings.flatMap((opening, openingIndex) =>
      scenario.followups.map((followup, followupIndex) => ({
        id: `editorial:${scenario.key}:${openingIndex + 1}:${followupIndex + 1}`,
        source: 'editorial' as const,
        tone: 'نموذج تمثيلي' as const,
        message: `${opening} ${followup}`,
        reply: '',
      })),
    ),
  )
}

type LetterMemory = { seen: string[]; recent: string[] }

function readMemory(): LetterMemory {
  if (typeof window === 'undefined') return { seen: [], recent: [] }
  try {
    const parsed = JSON.parse(window.localStorage.getItem(STORAGE_KEY) || '{}') as Partial<LetterMemory>
    return {
      seen: Array.isArray(parsed.seen) ? parsed.seen.filter((item): item is string => typeof item === 'string') : [],
      recent: Array.isArray(parsed.recent) ? parsed.recent.filter((item): item is string => typeof item === 'string') : [],
    }
  } catch {
    return { seen: [], recent: [] }
  }
}

function writeMemory(memory: LetterMemory) {
  if (typeof window === 'undefined') return
  try { window.localStorage.setItem(STORAGE_KEY, JSON.stringify(memory)) } catch { /* الذاكرة المرفوضة لا تمنع ظهور الرسائل */ }
}

/**
 * يعرض مجموعة جديدة في كل دخول للصفحة، ولا يعيد رسالة سبق عرضها ما دام في
 * المخزون بديل. بعد استهلاك المخزون يبدأ دورة جديدة مع حجب آخر مجموعة ظهرت.
 */
export function createEditorialLetterBatch(size = DEFAULT_BATCH_SIZE): EditorialLetter[] {
  const all = pool()
  const batchSize = Math.max(1, Math.min(Math.floor(size) || DEFAULT_BATCH_SIZE, all.length))
  const memory = readMemory()
  const seen = new Set(memory.seen)
  const recent = new Set(memory.recent)
  let available = all.filter((item) => !seen.has(item.id))

  if (available.length < batchSize) {
    available = all.filter((item) => !recent.has(item.id))
    if (available.length < batchSize) available = [...all]
    seen.clear()
  }

  const selected = shuffled(available, randomSeed()).slice(0, batchSize)
  selected.forEach((item) => seen.add(item.id))
  writeMemory({
    seen: [...seen].slice(-all.length),
    recent: selected.map((item) => item.id),
  })
  return selected
}

