import assert from 'node:assert/strict'
import { existsSync, readFileSync } from 'node:fs'

const source = readFileSync(new URL('../public/monteur/monteur.js', import.meta.url), 'utf8')
const tracks = [...source.matchAll(/url:"(\/music\/[a-z0-9-]+\.mp3)"/g)].map((match) => match[1])
assert.equal(tracks.length, 14, 'the monteur exposes the complete fourteen-track library')
assert.equal(new Set(tracks).size, tracks.length, 'music paths do not repeat')
for (const track of tracks) assert.ok(existsSync(new URL(`../${track.slice(1)}`, import.meta.url)), `missing ${track}`)
assert.match(source, /TRACK_POOLS=.*ai:/s, 'specialist themes have semantic music pools')
assert.match(source, /monteur:last-music:/, 'automatic selection remembers the previous article track')
assert.match(source, /packagePoster/, 'publishing package creates a vertical cover')
assert.match(source, /packageCaption/, 'publishing package creates concise posting copy')
assert.match(source, /navigator\.share/, 'publishing package uses the native share sheet when available')
assert.match(source, /living-cover\.webm/, 'publishing package includes a living cover when supported')
assert.match(source, /quality\.txt/, 'publishing package includes the post-export review')
assert.match(source, /MUSIC\[AU\.cur\].*vol|MUSIC\[AU\.cur\]\|\|\{\}\)\.vol/, 'track loudness is respected')
const specialistBackgrounds = [...source.matchAll(/url:'(\/covers\/monteur-[a-z0-9-]+-v2\.webp)'/g)].map((match) => match[1])
assert.equal(specialistBackgrounds.length, 10, 'ten new specialist backgrounds are registered')
assert.equal(new Set(specialistBackgrounds).size, 10, 'specialist background paths do not repeat')
for (const background of specialistBackgrounds) assert.ok(existsSync(new URL(`../${background.slice(1)}`, import.meta.url)), `missing ${background}`)
assert.match(source, /photoTarget=sc\.length>=9\?3:sc\.length>=5\?2:1/, 'articles and tweets receive a balanced photo quota')
assert.match(source, /function photoMatches/, 'cover backgrounds are scored against the source meaning')
assert.match(source, /cut==='symbolic'.*!s\.photo/, 'symbolic direction preserves selected photo scenes')
console.log('✓ مكتبة المونتير: 14 مقطوعة و10 خلفيات تخصصية جديدة وحزمة نشر ممتدة')
