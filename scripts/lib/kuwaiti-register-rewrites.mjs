export function applyApprovedRegisterRewrites (text, { slug = '' } = {}) {
  let value = String(text ?? '')
  const applied = []
  for (const rule of APPROVED_REGISTER_REWRITES) {
    if (rule.slug && rule.slug !== slug) continue
    rule.pattern.lastIndex = 0
    if (!rule.pattern.test(value)) continue
    rule.pattern.lastIndex = 0
    const next = value.replace(rule.pattern, rule.replacement)
    if (next !== value) {
      value = next
      applied.push(rule.id)
    }
  }
  return { text: value, applied }
}
