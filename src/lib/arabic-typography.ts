/**
 * قاعدة تحرير عربية موحّدة للموقع كله.
 *
 * أهم قرار أسلوبي للدكتور:
 * - تنوين الفتح يوضع على الألف دائماً: «مشروعاً».
 * - تنوين الضم والكسر يلتصقان بالحرف: «ممدوحٌ»، «كتابٍ».
 *
 * هذه الدالة محافظة: لا تحاول تخمين الإعراب، بل توحّد موضع علامة التنوين
 * وتزيل الفصل الطباعي الخاطئ، ثم تطبق تنظيفات النص العربية المعتادة.
 */
export function normalizeArabicTypography(input = ''): string {
  return input
    .normalize('NFC')
    /* تنوين الفتح: بعض المحررات تحفظ العلامة قبل ألف النصب؛ هوية الموقع تعتمد العكس. */
    .replace(/\u064B\u0627/g, '\u0627\u064B')
    /* لا تُفصل علامات التنوين الثلاثة عن الحرف بمسافة أو tab. */
    .replace(/([\u0621-\u064A\u0671-\u06D3])[ \t]+([\u064B-\u064D])/g, '$1$2')
    /* منع تكرار علامة التنوين نفسها بسبب النسخ أو اللصق. */
    .replace(/([\u064B-\u064D])\1+/g, '$1')
    /* ═══ آثار النسخ من Word ═══
       Word يلصق شفرة الحقل نفسها لا الرابط: «HYPERLINK «https://…» النص».
       فتظهر الكلمة الإنجليزية داخل نصٍ عربي منشور. نمسح شفرة الحقل ونُبقي
       النص الذي يليها كما كتبه الدكتور. ويشمل صيغ Word الأخرى: PAGEREF
       وREF ومحدِّدات \\o و\\l التي تتبع الرابط أحياناً. */
    .replace(/\s*HYPERLINK\s*(?:«[^»]*»|"[^"]*"|'[^']*'|\S+)(?:\s*\\[ol]\s*(?:"[^"]*"|\S+))*\s*/gi, ' ')
    .replace(/\s*(?:PAGEREF|NOTEREF|REF)\s+\S+(?:\s*\\[a-z]\s*)*/gi, ' ')
    .replace(/\u00a0/g, ' ')
    .replace(/\.\.\.+/g, '…')
    .replace(/\.\./g, '…')
    .replace(/[“”](.*?)[“”]/g, '«$1»')
    .replace(/(^|[\s(])"([^"\n]{2,})"(?=$|[\s،؛؟!.)])/g, '$1«$2»')
    .replace(/[ \t]+([،؛؟!])/g, '$1')
    .replace(/([،؛؟!])(?=[^\s\n»])/g, '$1 ')
    .replace(/[ \t]+\n/g, '\n')
    .replace(/\n{3,}/g, '\n\n')
    .trim()
}
